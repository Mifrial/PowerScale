/**
 * Модификатор действия. Список и подписи собирает сервер, фронт только показывает.
 */
export interface GameActionModifier {
  /** Карточка действия, к которой относится модификатор. */
  actionCode: string;
  /** Название карточки действия. */
  actionName: string;
  /** Код способности-модификатора. */
  code: string;
  /** Название способности. */
  name: string;
  /** Пояснение от сервера: проверка, сложность, последствия. */
  summary: string;
}
