/**
 * Опция после удара. Список и подписи собирает сервер, фронт только показывает.
 */
export interface GameActionOption {
  /** Карточка действия, к которой относится опция. */
  actionCode: string;
  /** Код способности-опции. */
  code: string;
  /** Название способности. */
  name: string;
  /** Пояснение от сервера: проверка, сложность, последствие. */
  summary: string;
}
