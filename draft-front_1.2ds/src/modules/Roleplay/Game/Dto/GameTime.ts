/**
 * Игровое время (ТР §8 «Летопись»): сдвиг от точки отсчёта в фиксированных игровых единицах
 * (1 год = 10 месяцев · месяц = 3 декады · декада = 10 дней · день = 30 часов · час = 60 минут;
 * минута — минимальная хранимая/отображаемая единица). Значения неотрицательные; каноническая
 * форма (`normalizeGameTime`) хранит максимально крупные единицы: 13 месяцев → 1 год 3 месяца,
 * поля не превышают «порог» следующей единицы (месяцы ≤ 9, минуты ≤ 59).
 * В перспективе единицы станут настройкой правил — конверсии локализованы в Utils/gameTime.
 */
export interface GameTime {
  years: number;
  months: number;
  decades: number;
  days: number;
  hours: number;
  minutes: number;
}
