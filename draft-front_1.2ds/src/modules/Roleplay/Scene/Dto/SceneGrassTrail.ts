/** След движения акторов, упакованный для шейдера ковра травы. */
export interface SceneGrassTrail {
  /** По четыре числа на точку: мировой x, мировой y, вектор потока (направление × сила). */
  spots: Float32Array;
  /** Сколько точек заполнено. */
  count: number;
  /** Высота ковра в единицах сцены: на ней пучок наклоняется полностью. */
  span: number;
  /** Полуширина полосы следа в единицах сцены. */
  width: number;
}
