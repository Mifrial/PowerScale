/**
 * Верх стены «до неба»: у старой стены высоты нет.
 *
 * Растр хранит верх в юнитах сцены в `Uint16Array`, поэтому бесконечность
 * заменена сентинелом. Любой реальный луч ниже него, и такая стена закрывает
 * взгляд, как раньше.
 */
export const SCENE_SIGHT_SKY = 0xffff;

/**
 * Растр перекрытия обзора на клетках поля.
 *
 * Запекается один раз при сборке препятствий этажа: стены, проёмы и плиты
 * становятся байтами, и на тике тумана не остаётся обращений к фигурам. Клетка
 * равна `occupancyCell` поля; массивы row-major, `index = row * columns + column`.
 */
export interface SceneSightRaster {
  /** Левый верхний угол растра в координатах поля. */
  x: number;
  y: number;
  /** Размер клетки в единицах сцены. */
  cell: number;
  columns: number;
  rows: number;
  /** `1` — клетка перекрывает взгляд. */
  cells: Uint8Array;
  /**
   * Верх перекрытия в единицах сцены: у стены — `props.height` над полом
   * этажа, у старой стены без высоты — `SCENE_SIGHT_SKY`.
   *
   * Луч выше этой отметки проходит поверх стены. Для плиты поле не значимо:
   * её перекрытие проверяется пересечением плоскости, а не высотой клетки.
   * У окна (`cells = 2`) это верх стены над перемычкой: вторая полоса идёт
   * от `lintels` до этой отметки.
   */
  tops: Uint16Array;
  /**
   * Низ окна в единицах сцены (`cells = 2`): верх подоконника.
   *
   * Окно — не дыра во всю стену: луч проходит только между подоконником и
   * перемычкой. Ниже подоконника стена, выше перемычки тоже, поэтому клетка
   * хранит две полосы, как клетка поверхности: `bottom…sills` и
   * `lintels…tops`. У глухой стены массив не нужен и не выделяется.
   */
  sills?: Uint16Array;
  /** Верх окна, низ перемычки (`cells = 2`), единицы сцены. */
  lintels?: Uint16Array;
}
