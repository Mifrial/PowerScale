/**
 * Актор на поле: стендалка с якорем в ногах.
 *
 * Позиция и состояние принадлежат игре; рендерер только рисует. `facing` —
 * 0–359°, 0 смотрит вверх экрана, дальше по часовой.
 */
export interface SceneActor {
  id: number;
  /** Мировой x точки под ногами. */
  x: number;
  /** Мировой y точки под ногами: по нему идёт Y-сортировка. */
  y: number;
  /** Куда смотрит, градусы. */
  facing: number;
  /** Радиус footprint в единицах сцены. */
  radius: number;
  /** Радиус обзора в единицах сцены; у предпросмотра задаётся отдельно. */
  sightRadius?: number;
  /** Тинт стендалки. */
  tint: number;
  label: string;
  /** Выбран в предпросмотре. */
  selected?: boolean;
  /** Призрак: скрыт от текущего наблюдателя, но виден ведущему. */
  ghost?: boolean;
  /** Уровень поверхности: 0 — земля, больше — настил. */
  level?: number;
  /** Стоит под более высокой поверхностью: рисуется приглушённо. */
  underDeck?: boolean;
}
