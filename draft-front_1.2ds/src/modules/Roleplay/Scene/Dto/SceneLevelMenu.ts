/** Вариант уровня в меню клика. */
export interface SceneLevelOption {
  /** Уровень навигации: 0 — земля, больше — настил. */
  level: number;
  /** Подпись: «Под настилом» или «На настил … ипари». */
  label: string;
}

/**
 * Меню выбора уровня под точкой клика.
 *
 * Появляется, когда под точкой есть и земля, и настил: обычный клик не может
 * решить, вести актёра наверх или оставить под настилом. Alt+клик всегда ведёт
 * по земле.
 */
export interface SceneLevelMenu {
  /** Смещение точки клика внутри холста, px. */
  x: number;
  y: number;
  options: SceneLevelOption[];
}
