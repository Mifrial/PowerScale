import type { ScenePoint } from '@/modules/Roleplay/Scene/Dto/ScenePoint';

/**
 * Отступ раскладки травы от контура острова.
 *
 * Берег острова — собственность воды: сухая полоса рисуется внутрь контура на
 * ширину берега, поэтому трава не должна на неё заходить. Контур уже
 * тесселирован: по нему же вода режет дырку в поле глубины.
 */
export interface SceneGrassInset {
  /** Замкнутый контур острова в единицах сцены. */
  contour: ScenePoint[];
  /** Ширина берега, единицы сцены. */
  distance: number;
}
