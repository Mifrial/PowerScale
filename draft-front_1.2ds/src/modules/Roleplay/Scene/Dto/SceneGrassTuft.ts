/** Пучок травы: точка на земле, вариант атласа и вариация вида. */
export interface SceneGrassTuft {
  /** Мировой x основания. */
  x: number;
  /** Мировой y основания: по нему идёт Y-сортировка. */
  y: number;
  /** Номер варианта в атласе. */
  variant: number;
  /** Высота пучка в единицах сцены. */
  height: number;
  /** Отразить по горизонтали. */
  flip: boolean;
  /** Небольшой наклон, радианы. */
  rotation: number;
  /** Затемнение спрайта. */
  tint: number;
  /** Прозрачность спрайта. */
  alpha: number;
  /** Порядок создания: тайбрейкер при равном y. */
  sequence: number;
}
