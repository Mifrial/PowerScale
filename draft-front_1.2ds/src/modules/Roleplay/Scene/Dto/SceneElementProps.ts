import type { SceneFootprint, SceneSilhouette } from '@/modules/Roleplay/Scene/Dto/SceneFootprint';

/** Свойства элемента; набор зависит от kind. */
export interface SceneElementProps {
  kind?: string;
  height?: number;
  /** Скорость поверхности: 100 — норма, 0 — непроходимо. */
  speed?: number;
  elevation?: number;
  blocksMovement?: boolean;
  blocksVision?: boolean;
  state?: 'open' | 'closed';
  label?: string;
  rotation?: number;
  scale?: number;
  /** Радиус основания декора, проценты видимой ширины спрайта: ход и ствол. */
  baseRadius?: number;
  /** Радиус силуэта декора, проценты видимой ширины спрайта: крона, валун. */
  sightRadius?: number;
  /** Низ силуэта, проценты видимой ширины спрайта: 0 — стоит на земле. */
  sightBottom?: number;
  /** Основание декора в единицах сцены: круг или полигон от якоря. */
  footprint?: SceneFootprint;
  /** Силуэт декора в единицах сцены: форма перекрытия обзора и его низ. */
  silhouette?: SceneSilhouette;
  role?: string;
  assetPublicId?: string;
  /**
   * Материал стены: `plaster`, `wood`, `log`, `brick`, `stone`.
   *
   * Есть только у стены-ленты: сверху видна её полоса, и материал задаёт тон,
   * ребро, фаску и швы. У прочих препятствий верх не рисуется, и поле
   * отбрасывается при сохранении.
   */
  material?: string;
  shoreKind?: string;
  shoreWidth?: number;
  /**
   * Глубина воды в единицах сцены: насколько русло ниже берега.
   *
   * `0` — вода вровень с берегом, как в старых сценах. Врезанное русло
   * опускает поверхность воды, а береговая полоса (`shoreWidth`) становится
   * наклонным откосом от берега к урезу.
   */
  depth?: number;
  /**
   * Террейн лежит поверх воды: остров, насыпь, полуостров.
   *
   * Вода рисуется над сушей, поэтому без этого признака трава-остров утонула
   * бы под озером. Контур с признаком перекрывает воду и в рисунке, и в сетке
   * поверхностей.
   */
  overWater?: boolean;
  /**
   * Стена, в которую вставлен проём, id элемента.
   *
   * Поле живёт только в редакторе: при сохранении оно срезается, а при
   * загрузке привязка восстанавливается по геометрии. Так проём следует за
   * стеной при перетаскивании и не зависит от временных id.
   */
  wallId?: number;
  /**
   * Начало проёма вдоль осевой стены, единицы сцены от её первой вершины.
   *
   * Вместе с длиной проёма (расстояние между его концами) задаёт вырез в
   * стене. Поле тоже редакторское и при сохранении не пишется.
   */
  offset?: number;
  /**
   * Подоконник окна: высота, ниже которой окно перекрывает обзор.
   *
   * Ход окно не открывает никогда: через него видно, но не пройти. Ноль —
   * витрина от пола.
   */
  sill?: number;
  /** Перемычка окна: высота, выше которой начинается стена над проёмом. */
  lintel?: number;
  /**
   * По крыше можно ходить.
   *
   * Обычная крыша — потолок: полом под ногами она не становится. С признаком
   * крыша идёт путём настила — поверхностью на своей высоте, — и попасть на
   * неё можно лестницей или люком с верхнего этажа.
   */
  walkable?: boolean;
  /**
   * Перила лестницы: полосы по длинным сторонам марша.
   *
   * Они выше ступеней на `SCENE_BRIDGE.railHeightIpari` и участвуют в
   * навигации как отдельный уровень: с марша не спрыгнуть сбоку и по перилам
   * не пройти, а вход и выход остаются с торцов. По умолчанию выключены —
   * узкий марш в клетке стен перил не требует.
   */
  railing?: boolean;
}
