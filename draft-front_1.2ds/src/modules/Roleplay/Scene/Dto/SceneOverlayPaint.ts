/** Прямоугольная заливка оверлея в мировых координатах. */
export interface SceneOverlayBand {
  x: number;
  y: number;
  width: number;
  height: number;
  color: number;
  alpha: number;
}

/**
 * Маска тумана: тексели мельче клетки поля.
 *
 * Видимость считается по `occupancyCell`, а маска на маленьких полях рисуется
 * в `fogScale` текселей на клетку и размывается на `fogBlurIpari`. На большом
 * корне остаётся базовая маска, чтобы пересчёт не стоил десятки миллисекунд.
 * Рендерер растягивает маску на сетку и включает линейную фильтрацию.
 */
export interface SceneOverlayMask {
  /** Левый верхний угол сетки в мировых координатах. */
  x: number;
  y: number;
  /** Размер клетки в единицах сцены. */
  cell: number;
  columns: number;
  rows: number;
  /** Альфа тумана по клеткам, row-major: 0 — клетка видна. */
  alpha: Uint8Array;
  /** Цвет тумана. */
  color: number;
}

/**
 * Готовая картинка оверлеев одного поля.
 *
 * Два набора разделены по слоям: стоимость — авторская подсказка поверх
 * декора, чтобы непроходимые клетки читались сквозь траву; туман видимости —
 * маска над миром, поэтому затемняет и траву, и деревья.
 *
 * Туман считается на всех видимых этажах, поэтому рендерер получает набор
 * картинок: у каждого поля своя маска в его координатах.
 */
export interface SceneOverlayPaint {
  /** Поле, в координатах которого нарисованы полосы и маска. */
  boardId: number;
  /** Клетки стоимости: авторская подсказка поверх декора. */
  costs: SceneOverlayBand[];
  /** Скрытые клетки: маска над декором; `null` — туман выключен. */
  fog: SceneOverlayMask | null;
}
