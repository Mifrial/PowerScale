import type { ScenePoint } from '@/modules/Roleplay/Scene/Dto/ScenePoint';

/**
 * Наклон съезда: высота меняется вдоль длинной стороны.
 *
 * Низкий конец садится на поверхность под съездом, высокий берётся из
 * `props.elevation`. Навигация считает по наклону перепад у края, поэтому
 * низкий конец даёт шаг, а высокий — подъём или спуск.
 */
export interface SceneRampSlope {
  /** Точка низкого конца. */
  from: ScenePoint;
  /** Точка высокого конца. */
  to: ScenePoint;
  /** Высота низкого конца, единицы сцены. */
  low: number;
  /** Высота высокого конца, единицы сцены. */
  high: number;
}
