import type { SceneSurfaceKind } from '@/modules/Roleplay/Scene/Dto/SceneSurfaceKind';

/**
 * Сетка поверхностей поля.
 *
 * Клетка равна `occupancyCell` поля и не зависит от пикселей рендера: по этой
 * сетке считаются маршруты и видимость, а рендерер только рисует результат.
 * Все массивы row-major, `index = row * columns + column`.
 */
export interface SceneSurfaceGrid {
  /** Размер клетки в единицах сцены. */
  cell: number;
  /** Разрешение поля: единиц сцены в одной ипари. */
  resolution: number;
  /** Левый верхний угол сетки в единицах сцены. */
  x: number;
  y: number;
  columns: number;
  rows: number;
  /** Тип поверхности клетки. */
  kinds: SceneSurfaceKind[];
  /** Множитель скорости: 0 — непроходимо, больше — быстрее. */
  speeds: number[];
  /** Стоимость прохода клетки: `1 / speeds`; `Infinity` — непроходимо. */
  costs: number[];
  /**
   * Высота верхней поверхности клетки над нулём поля, единицы сцены.
   *
   * Настил перекрывает клетку и поднимает её: под мостом лежит вода или
   * берег со своей высотой, а ходят по настилу. Высота нужна Game для рёбер
   * доступа и для зазора под опорой.
   */
  elevation: Float32Array;
  /**
   * Поверхность под клеткой, единицы сцены: пол под настилом.
   *
   * Настил поднимает `elevation`, но не стирает то, что под ним: вода, берег,
   * дорога. Обзор с базового уровня стартует от этой высоты, а не от настила.
   */
  ground: Float32Array;
  /**
   * Нижний настил под верхней поверхностью клетки, единицы сцены; `NaN` — его нет.
   *
   * Нужен, когда настилы стоят друг над другом: марш внутри дома под
   * проходимой крышей. `elevation` хранит верхнюю поверхность (крышу), а здесь
   * остаётся марш, по которому идут на уровне 1. Без этого `surfaceFloor(1)`
   * поднимал бы глаз на крышу и туман «ломался» бы уже внизу лестницы.
   */
  deck: Float32Array;
  /**
   * Свободная высота над поверхностью клетки до ближайшего потолка, единицы
   * сцены; `Infinity` — открытое небо.
   *
   * Заполняется только под настилом: это зазор, в который должно поместиться
   * тело. Отрицательное значение — настил лежит на поверхности или ниже неё,
   * прохода под ним нет.
   */
  clearance: Float32Array;
  /**
   * Высота в ипари, с которой клетка перекрывает обзор.
   *
   * `0` — силуэт стоит на земле (ствол, валун, стена), `Infinity` — клетка
   * прозрачна. Крона дерева начинается выше глаз, поэтому луч под ней её
   * игнорирует.
   */
  sightBottom: Float32Array;
  /**
   * Высота в ипари, до которой клетка перекрывает обзор.
   *
   * Вместе с `sightBottom` задаёт полосу. Пустая клетка — `sightBottom` равно
   * `Infinity`, `sightTop` равно `-Infinity`: так объединение полос остаётся
   * объединением, а не «до неба». Настил перекрывает только свою толщину,
   * поэтому на мосту и под мостом видно по-своему, а сквозь настил — нет.
   */
  sightTop: Float32Array;
  /**
   * Низ второй полосы перекрытия, ипари.
   *
   * Нужна окну: у него две полосы — подоконник и перемычка, а между ними
   * проём. Одной полосой это не описать: объединение дало бы стену от пола до
   * неба, и окно перестало бы просвечивать. Пустая вторая полоса — `Infinity`,
   * как и у первой.
   */
  sightBottom2: Float32Array;
  /**
   * Верх второй полосы перекрытия, ипари.
   *
   * У перемычки окна верх — небо: выше неё стена до потолка, а потолок в
   * сетке не хранится. Пустая вторая полоса — `-Infinity`.
   */
  sightTop2: Float32Array;
}
