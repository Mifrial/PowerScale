/**
 * Материалы стены-ленты: тон верхней грани, обводка и швы.
 *
 * Стена видна сверху, поэтому материал — это ровная верхняя грань: один тон,
 * тёмная обводка по контуру силуэта и швы материала. Полос вдоль стены нет:
 * светлая фаска и линия по осевой делали стену полой коробкой с бликом, а не
 * монолитом. Объём даёт тень на полу.
 */
