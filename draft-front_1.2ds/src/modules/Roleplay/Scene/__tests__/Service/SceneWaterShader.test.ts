describe('шейдеры воды', () => {
  it('отдаёт сэмплеры как TextureSource, иначе Pixi их не привяжет', () => {
    const body = new SceneWaterBodyShader().create(bodyOptions());
    const surface = new SceneWaterSurfaceShader().create(surfaceOptions());

    // GL-синхронизация Pixi биндит только TextureSource и TextureView:
    // обёртка Texture молча пропускается, и сэмплер остаётся пустым.
    expect(body.shader.resources.uField).toBeInstanceOf(TextureSource);
    expect(body.shader.resources.uBed).toBeInstanceOf(TextureSource);
    expect(body.shader.resources.uSand).toBeInstanceOf(TextureSource);
    expect(surface.shader.resources.uField).toBeInstanceOf(TextureSource);
  });

  it('речные шейдеры отдают сэмплеры песка и пены', () => {
    const body = new SceneRiverBodyShader().create(riverBodyOptions());
    const surface = new SceneRiverSurfaceShader().create(riverSurfaceOptions());

    expect(body.shader.resources.uField).toBeInstanceOf(TextureSource);
    expect(body.shader.resources.uBed).toBeInstanceOf(TextureSource);
    expect(body.shader.resources.uSand).toBeInstanceOf(TextureSource);
    expect(surface.shader.resources.uField).toBeInstanceOf(TextureSource);
    expect(surface.shader.resources.uFoam).toBeInstanceOf(TextureSource);
  });
});
