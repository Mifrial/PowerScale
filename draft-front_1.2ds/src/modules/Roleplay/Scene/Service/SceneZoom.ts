/** Доля изменения зума, после которой слои надо пересобрать. */
export const SCENE_ZOOM_REBUILD_SHARE = 0.03;

/**
 * Пауза между пересборками при непрерывном зуме, мс.
 *
 * Пересборка слоёв — это заново вся сцена: стены, террейн, трава, тени и
 * пороги. На каждое событие колеса её делать нельзя, иначе зум заметно
 * лагает. За паузу колесо успевает прислать пачку смен, и сцена собирается
 * один раз — картинка догоняет масштаб, но кадры не проваливаются.
 */
export const SCENE_ZOOM_REBUILD_MS = 140;

/**
 * Нужно ли пересобрать слои под новый зум.
 *
 * Сравниваем с зумом, под который слои уже собраны, а не с предыдущим
 * событием колеса: толщины линий и тени считаются при сборке, поэтому при
 * плавном приближении их надо обновлять до двукратного шага. Порог в три
 * процента отсекает дрожание, но не даёт картинке «поплыть».
 */
export function sceneZoomNeedsRebuild(builtZoom: number, zoom: number): boolean {
  if (!Number.isFinite(builtZoom) || !Number.isFinite(zoom) || builtZoom <= 0 || zoom <= 0) {
    return false;
  }

  return Math.abs(zoom / builtZoom - 1) > SCENE_ZOOM_REBUILD_SHARE;
}
