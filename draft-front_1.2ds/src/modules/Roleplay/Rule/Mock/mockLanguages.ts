function languageRule(
  id: number,
  code: string,
  name: string,
  description: string,
  role: LanguageRole,
  parentCode: string | null,
  scriptCodes: string[] = [],
): Rule {
  return {
    id,
    code,
    type: 'language',
    name,
    description,
    spaceId: 1,
    spec: { type: 'language', role, parent_code: parentCode, script_codes: scriptCodes },
    keywordIds: [],
    mechanicId: null,
    mechanicPayload: null,
    createdAt: 1786356000,
  };
}

