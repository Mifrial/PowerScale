/**
 * Контекст броска, видимый механикам (draft): хендлеры событий ролла (`ROLL_EVENTS`)
 * мутируют его. Поля зеркалят результат RollEngine; «базовый подсчёт» (≤ сложность → 1)
 * — примитив движка, механики добавляют кубы (`pool`/`drop`) и дельты успехов (`score`).
 */
export interface RollMechanicContext {
  /** Базовые параметры спеки броска. */
  diceCount: number;
  dieFaces: number;
  efficiency: number;
  /** Преимущества (>0) / помехи (<0); 0 — пул не меняется. */
  adv: number;
  /** Число кубов для броска: `roll.pool` добавляет лишние (Помехи/Преимущества). */
  poolSize: number;
  /** Значения всех брошенных кубов (до отбрасывания худших/лучших). */
  rolls: number[];
  /** Кубы после отбрасывания (`roll.drop`); совпадает с `rolls`, если механика не сработала. */
  adjustedRolls: number[];
  droppedRolls: number[];
  /** Успехи по кубам после базового подсчёта (`roll.score` добавляет/снимает). */
  successes: number[];
  totalSuccesses: number;
  /** Коды механик, реально повлиявших на бросок (для чипов результата). */
  applied: string[];
}
