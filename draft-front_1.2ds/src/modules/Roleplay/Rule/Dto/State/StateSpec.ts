import type { StateEffect } from '@/modules/Roleplay/Rule/Dto/State/StateEffect';

export type StateValueType = 'flag' | 'number' | 'dimensional';

/** Как объединяются повторы одного правила в списке состояний персонажа. */
export type StateAggregation = 'sum' | 'max' | 'independent';

/**
 * Спека состояния (type='state'): как хранится текущее значение на персонаже
 * (value_type) и какие эффекты состояние оказывает. Источник истины для карточки
 * и для применения эффектов в Обзоре (Phase 2).
 */
export interface StateSpec {
  /** mdi-иконка для ориентации в блоке «Состояния» и списках правил. */
  icon_code?: string | null;
  /**
   * flag        — наличие (есть/нет)
   * number      — целое число
   * dimensional — одно размерное число
   */
  value_type: StateValueType;
  /**
   * Повторы одного правила в списке состояний объединяются по aggregation:
   * sum        — значения суммируются (Горение)
   * max        — берётся наибольшее (Слабость)
   * independent— каждая запись действует отдельно (Раны, каждая со своим значением)
   */
  aggregation: StateAggregation;
  /**
   * Коды способностей-действий, которые попап записи состояния предлагает открыть
   * в диалоге «Действие» (цель и индекс записи подставляются).
   */
  action_codes?: string[];
  /** Проверка, которую бросает процедура этого состояния. Нет поля — проверки нет. */
  check_code?: string | null;
  /** Остаток повреждений, не добравший целую стойкость. Нет флага — запись не ведётся. */
  damage_remainder?: boolean;
  /** Куда писать истощение от повреждений. Нет флага — истощение не пишется. */
  damage_exhaustion?: boolean;
  /** Шкала кровопотери. Резерв истощения = floor(значение / 10). Нет флага — тик не ведётся. */
  blood_loss?: boolean;
  /** Исход упадка сил при РУ −1. Нет флага — состояние не пишется. */
  decline_weakness?: boolean;
  /** Исход упадка сил при РУ −2. Нет флага — состояние не пишется. */
  decline_disabled?: boolean;
  /** Исход упадка сил при РУ ≤ −3. Нет флага — проверка при росте истощения не пропускается. */
  decline_unconscious?: boolean;
  /** Куда писать силу увечья. Нет флага — запись не ведётся. */
  maim?: boolean;
  /** Тик горения из эффекта damage_over_time. Нет флага — тик не идёт. */
  burning?: boolean;
  /** Носитель отравления: тик из записи poison и редактор яда на карточке. Нет флага — тик не идёт. */
  poisoning?: boolean;
  /** Лежачее положение. Нет флага — поза его не читает и не пишет. */
  lying?: boolean;
  /** Шкала неустойчивости. Нет флага — прирост и снятие не ведутся. */
  unstable?: boolean;
  /** Отклонение на ядре после провала сотворения. Нет флага — не пишется и не затухает. */
  magic_deviation?: boolean;
  effects?: StateEffect[];
}
