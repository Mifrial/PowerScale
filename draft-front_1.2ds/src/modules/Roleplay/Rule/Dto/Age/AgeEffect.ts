/** Эффект возрастной ступени: модификатор характеристики «от возраста». */
export interface AgeEffect {
  /** Код характеристики (производная — применяется к её базам). */
  characteristic_code: string;
  /** Смещение в пунктах шкалы характеристики (размерность применяется через CharacteristicNumber). */
  delta: number;
  /** Условность: модификатор не входит в значение, помечается в попапе («для проверок на усвоение нового»). */
  scope?: string | null;
}
