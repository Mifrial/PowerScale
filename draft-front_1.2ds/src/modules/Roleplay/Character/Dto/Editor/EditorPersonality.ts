/** Сводка «Личности» в модели редактора: возраст, ОЛ/лимит, особенности богатства. */
export interface EditorPersonality {
  /** В ревизии есть правило «возраст» (иначе этапа «Личность» нет). */
  hasAgeRule: boolean;
  /** Годы персонажа (null — возраст не выбран). */
  ageYears: number | null;
  /** Имя ступени возраста (null — не определена). */
  ageName: string | null;
  /** ОЛ от ступени возраста (null — ступень не определена). */
  ol: number | null;
  /** Лимит числа особенностей личности (без признака «Богатство»; null — не определён). */
  featureLimit: number | null;
  /** ruleId особенностей богатства: не учитываются в лимите числа особенностей. */
  wealthRuleIds: string[];
  /**
   * Шкала возраста вида/расы в порядке ступеней правила: диапазон лет каждой ступени.
   * min всегда задан; max null — открытый диапазон («Старый»). У «Младенца» min = 0.
   */
  ageScale: { name: string; min: number; max: number | null }[];
  /**
   * Дефолт возраста по умолчанию: минимум средней ступени шкалы (отсортированной по min) —
   * «Молодой» в стандартной таблице. null — у расы нет таблицы лет (возраст не выбирать).
   */
  defaultAgeYears: number | null;
}
