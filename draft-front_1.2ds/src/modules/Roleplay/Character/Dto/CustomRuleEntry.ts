/**
 * Запись кастомного правила на персонаже («Уникальные правила»). Выдаётся ведущим «на ходу»
 * как чистая текстовая запись (имя + описание) без привязки к правилу ревизии — поэтому не
 * требует поддержки в чатах/слайдерах/бюджетах/модерации и переживает смену ревизии без ломки.
 *
 * Жизненный цикл: `active` (выдано) → «Оформить как правило» (ведущий создаёт правило в черновике
 * и коммитит) → «Заменить на правило» (запись становится `deprecated` и ссылается на настоящее
 * правило ревизии через `replacedWithRuleId`).
 */
export interface CustomRuleEntry {
  id: number;
  /** Тип записи по смыслу: предмет или способность (для фильтра/иконки). */
  kind: 'item' | 'ability';
  name: string;
  description: string | null;
  status: 'active' | 'deprecated';
  /** ruleId правила, на которое заменена устаревшая запись (после «Заменить на правило»). */
  replacedWithRuleId?: string;
}
