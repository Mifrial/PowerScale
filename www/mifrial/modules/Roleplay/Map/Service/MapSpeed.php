<?php

declare(strict_types=1);

namespace Mifrial\Roleplay\Map\Service;

/**
 * Шкала проходимости карты.
 *
 * Скорость хранится в сотых: 5000 — обычная земля, 10000 — каменная дорога,
 * 0 — непроходимо. Дробная шкала нужна, чтобы редкие штрафы не упирались в единицу.
 */
final class MapSpeed
{
    /**
     * Максимальная скорость.
     */
    public const MAX = 10000;

    /**
     * Обычная земля без разметки.
     */
    public const DEFAULT = 5000;

    /**
     * Множитель стоимости шага: 10000 / скорость.
     */
    public const COST_FACTOR = 10000;
}
